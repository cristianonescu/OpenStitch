#!/usr/bin/env python3
"""Generates crates/openstitch-core/src/brands.rs from thread-chart CSVs (B16.1 T5).

    python3 -I tools/gen_brand_charts.py crates/openstitch-core/data/brands && cargo fmt --all

The directory holds one CSV per chart with OpenStitch's thread-chart
columns `code,brand,description,R,G,B`, and a `charts.txt` listing `file|id|display name` lines
(the CSV's name without `.csv`, the chart id, its name) in the order the charts are offered. A
colour without a description is named by its code. The colour values are the manufacturers' own published values; where
each came from is recorded in docs/research/beyond/thread-charts.md.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "openstitch-core" / "src" / "brands.rs"


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    src = Path(sys.argv[1])
    charts = [l.split("|", 2) for l in (src / "charts.txt").read_text(encoding="utf-8").splitlines() if l.strip()]
    out = [
        "// Generated by tools/gen_brand_charts.py. Colour values are the manufacturers' own published",
        "// values, as facts; sources in docs/research/beyond/thread-charts.md.",
        "",
        "//! Other brands' thread charts (B16.1 T5), for OpenStitch mode's image wizards to choose",
        "//! threads from. The PES/PEC chart ([`crate::PEC_CHART`]) and its matching are not changed.",
        "",
        "use crate::Thread;",
        "",
    ]
    statics = []
    for file, cid, name in charts:
        rows = list(csv.DictReader((src / f"{file}.csv").open(encoding="utf-8")))
        ident = file.upper().replace("-", "_")
        out.append(f"/// {name}: {len(rows)} colours.")
        out.append(f"pub static {ident}: [Thread; {len(rows)}] = [")
        for r in rows:
            out.append(
                f"    Thread::chart({int(r['R'])}, {int(r['G'])}, {int(r['B'])}, "
                f"{lit(r['description'] or r['code'])}, {lit(r['code'])}, {lit(r['brand'])}),"
            )
        out.append("];")
        out.append("")
        statics.append((cid, name, ident))
    out.append("/// Every brand chart here: id, display name, threads, in the order they are offered.")
    out.append(f"pub fn brand_charts() -> [(&'static str, &'static str, &'static [Thread]); {len(statics)}] {{")
    out.append("    [")
    for cid, name, ident in statics:
        out.append(f"        ({lit(cid)}, {lit(name)}, &{ident}),")
    out.append("    ]")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(statics)} charts")


if __name__ == "__main__":
    main()
